WITH TMP AS (
SELECT E.EMP_NO AS EMP_NO, SUM(G.SCORE) AS SCORE
FROM HR_EMPLOYEES E JOIN HR_GRADE G
ON E.EMP_NO = G.EMP_NO
WHERE G.YEAR = 2022
GROUP BY E.EMP_NO
ORDER BY SUM(G.SCORE) DESC
LIMIT 1)

SELECT T.SCORE, E.EMP_NO, E.EMP_NAME, E.POSITION, E.EMAIL
FROM TMP T JOIN HR_EMPLOYEES E
ON T.EMP_NO = E.EMP_NO;

