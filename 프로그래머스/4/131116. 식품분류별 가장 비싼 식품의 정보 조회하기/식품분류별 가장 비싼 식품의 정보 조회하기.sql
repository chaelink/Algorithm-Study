WITH TMP AS (SELECT CATEGORY, MAX(PRICE) AS PRICE
FROM FOOD_PRODUCT 
GROUP BY CATEGORY
HAVING CATEGORY IN ('과자', '국', '김치', '식용유'))

SELECT P.CATEGORY, T.PRICE AS MAX_PRICE, P.PRODUCT_NAME
FROM FOOD_PRODUCT P JOIN TMP T
ON P.PRICE = T.PRICE AND P.CATEGORY = T.CATEGORY
ORDER BY P.PRICE DESC;

